let L = "lo";
try {
  const savedLanguage = localStorage.getItem("glp-lang");
  if (savedLanguage === "lo" || savedLanguage === "en") L = savedLanguage;
} catch (error) {
  console.warn("Could not read the saved language preference.", error);
}
let guideIndex = 0;

function renderWasteGuide() {
  const category = wasteCategories[guideIndex];
  const languageIndex = L === "lo" ? 0 : 1;
  const accent = category.color;
  const card = document.getElementById("waste-guide-card");
  const guideContent = document.getElementById("waste-guide-content");

  card.style.setProperty("--bin-accent", accent);
  card.style.setProperty("--bin-tint", category.tint);
  document.getElementById("guide-step").textContent =
    `${String(guideIndex + 1).padStart(2, "0")} / ${String(wasteCategories.length).padStart(2, "0")}`;

  const image = document.getElementById("guide-bin-image");
  image.src = category.image;
  image.alt = `${category.binLabel[languageIndex]} — ${category.name[languageIndex]}`;
  document.getElementById("guide-category").textContent =
    category.binLabel[languageIndex];
  document.getElementById("guide-category").style.backgroundColor =
    category.tint;
  document.getElementById("guide-category").style.color = accent;
  document.getElementById("guide-title").textContent =
    category.name[languageIndex];
  document.getElementById("guide-purpose").textContent =
    category.purpose[languageIndex];
  document.getElementById("guide-tip-title").querySelector("span").textContent =
    category.tipTitle[languageIndex];
  document.getElementById("guide-tip").textContent =
    category.tip[languageIndex];
  document.getElementById("guide-tip-box").style.borderLeftColor = accent;
  document.getElementById("guide-next").style.backgroundColor = accent;
  document.getElementById("guide-count").textContent =
    `${String(guideIndex + 1).padStart(2, "0")} / ${String(wasteCategories.length).padStart(2, "0")}`;

  const examples = document.getElementById("guide-examples");
  examples.replaceChildren(
    ...category.examples.map((example) => {
      const item = document.createElement("li");
      item.className =
        "flex items-center gap-3 rounded-xl border border-deep/10 bg-white px-3 py-3 text-sm text-deep";
      const icon = document.createElement("i");
      icon.className = `${example.icon} text-lg`;
      icon.style.color = accent;
      icon.setAttribute("aria-hidden", "true");
      const label = document.createElement("span");
      label.textContent = example.name[languageIndex];
      item.append(icon, label);
      return item;
    }),
  );

  const progress = document.getElementById("guide-progress");
  progress.setAttribute(
    "aria-label",
    L === "lo" ? "ຄວາມຄືບໜ້າຂອງຄູ່ມື" : "Waste guide progress",
  );
  progress.replaceChildren(
    ...wasteCategories.map((step, index) => {
      const indicator = document.createElement("span");
      indicator.className =
        "h-2.5 rounded-full transition-all duration-300";
      indicator.style.backgroundColor =
        index === guideIndex ? step.color : "#d1d5db";
      indicator.style.width = index === guideIndex ? "2rem" : "0.625rem";
      indicator.setAttribute(
        "aria-label",
        `${L === "lo" ? "ຂັ້ນຕອນ" : "Step"} ${index + 1}: ${step.name[languageIndex]}`,
      );
      if (index === guideIndex) indicator.setAttribute("aria-current", "step");
      return indicator;
    }),
  );

  document.getElementById("guide-previous").disabled = guideIndex === 0;
  document.getElementById("guide-next").disabled =
    guideIndex === wasteCategories.length - 1;
  guideContent.classList.remove("is-changing");
  void guideContent.offsetWidth;
  guideContent.classList.add("is-changing");
}

function renderWastePage() {
  document.documentElement.lang = L;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (T[key]) {
      el.innerHTML = T[key][L === "lo" ? 0 : 1];
    }
  });
  document.querySelectorAll("[data-lang]").forEach((b) => {
    const active = b.dataset.lang === L;
    b.classList.toggle("act", active);
    b.setAttribute("aria-pressed", String(active));
  });
  renderWasteGuide();
}

document.addEventListener("click", (e) => {
  const b = e.target.closest("[data-lang]");
  if (b) {
    L = b.dataset.lang;
    try {
      localStorage.setItem("glp-lang", L);
    } catch (error) {
      console.warn("Could not save the language preference.", error);
    }
    renderWastePage();
  }
});

document.getElementById("guide-previous").addEventListener("click", () => {
  if (guideIndex > 0) {
    guideIndex -= 1;
    renderWasteGuide();
  }
});

document.getElementById("guide-next").addEventListener("click", () => {
  if (guideIndex < wasteCategories.length - 1) {
    guideIndex += 1;
    renderWasteGuide();
  }
});

renderWastePage();
