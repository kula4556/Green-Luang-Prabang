function endIntro(go) {
  try {
    sessionStorage.setItem("glp-intro", "1");
  } catch (e) {}
  intro.style.transition = "opacity .6s";
  intro.style.opacity = 0;
  document.body.classList.remove("lock");
  setTimeout(() => {
    intro.style.display = "none";
    if (!rm && heroContent) heroContent.classList.add("is-entering");
    if (go) location.hash = "#about";
  }, 600);
}
$("#skip").onclick = () => endIntro(false);
$("#enter").onclick = () => endIntro(true);
