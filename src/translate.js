const $ = (s) => document.querySelector(s),
  $$ = (s) => [...document.querySelectorAll(s)];
let L = "lo";
try {
  L = localStorage.getItem("glp-lang") || "lo";
} catch (e) {}
const t = (k) => T[k][L === "lo" ? 0 : 1];

function render() {
  document.documentElement.lang = L;
  $$("[data-i18n]").forEach((e) => (e.innerHTML = t(e.dataset.i18n)));
  $$("[data-lang]").forEach((b) => {
    b.classList.toggle("act", b.dataset.lang === L);
    b.setAttribute("aria-pressed", b.dataset.lang === L);
  });
  $("#mp").innerHTML = NAV.map(
    (k) =>
      `<a href="#${k}" class="group flex items-center justify-between rounded-2xl px-5 py-3 font-medium hover:bg-white/10"><span class="relative after:absolute after:-bottom-1 after:left-0 after:h-px after:w-full after:origin-left after:scale-x-75 after:bg-white after:transition-transform after:duration-300 group-hover:after:scale-x-100 group-focus-visible:after:scale-x-100">${t("nav_" + k)}</span><i class="ri-arrow-right-line transition-transform duration-300 group-hover:translate-x-1 group-focus-visible:translate-x-1" aria-hidden="true"></i></a>`,
  ).join("");
}
