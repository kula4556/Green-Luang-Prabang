document.addEventListener("click", (e) => {
  const b = e.target.closest("button,a");
  if (!b) return;
  if (b.dataset.lang) {
    L = b.dataset.lang;
    try {
      localStorage.setItem("glp-lang", L);
    } catch (x) {}
    render();
  } else if ("donate" in b.dataset) {
    donate();
    closeMenu();
  } else if (b.closest("#mp")) closeMenu();
});
